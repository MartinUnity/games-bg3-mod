local campers = {}
local function hostAtCamp()
    local host = Osi.GetHostCharacter()
    return host ~= nil and host ~= "" and campers[tostring(host)] == true
end

local function rand(lo, hi) return math.random(lo, hi) end

-- region theme for the current level (nil = default mix)
local function themeFor(level)
    for _, th in ipairs(WILD_THEMES) do
        if level:find(th.pat) then return th end
    end
    return nil
end

-- does a DB entry fit the theme? (terms = case-insensitive substrings of the id)
local function themeMatch(th, e, typeName)
    if th.types and th.types[typeName] then return true end
    if th.terms then
        local id = e.id:lower()
        for _, term in ipairs(th.terms) do
            if id:find(term, 1, true) then return true end
        end
    end
    return false
end

-- combined, level-gated pool of every DB entry matching the theme
local function themedPoolFor(th, base)
    local out = {}
    for t, _ in pairs(CHAOS_DB) do
        local gated = gatedPool(t, base)
        if gated then
            for _, e in ipairs(gated) do
                if themeMatch(th, e, t) then out[#out + 1] = e end
            end
        end
    end
    return out
end

-- pick a mob type that has entries for this level (no fight to classify - demographic
-- targeting by region is deferred per owner; for now a random pool type)
local function wildType(base)
    local opts = {}
    for _, t in ipairs(DEFAULT_TYPES) do
        if gatedPool(t, base) then opts[#opts + 1] = t end
    end
    if #opts == 0 then return nil end
    return opts[rand(1, #opts)]
end

-- pick a valid, out-of-sight group spot: random angle/radius, then FindValidPosition
-- corrects the raw point to the nearest walkable ground within WILD_SPOT_SLACK; if the
-- correction is bigger than that (target was inside a wall / off the map - common in
-- cramped TUT interiors), try another angle.
local function findGroupSpot(px, py, pz, host)
    for _ = 1, WILD_SPOT_TRIES do
        local angle = math.random() * 2 * math.pi
        local radius = rand(WILD_SPAWN_MIN, WILD_SPAWN_MAX)
        local tx, tz = px + math.cos(angle) * radius, pz + math.sin(angle) * radius
        local ok, vx, vy, vz = pcall(Osi.FindValidPosition, tx, py, tz, WILD_SPOT_SLACK, host, 1)
        if ok and type(vx) == "number" then
            -- 3D drift: FindValidPosition can snap DOWN a floor through a ceiling -
            -- in-game 2026-10-31 a patrol spawned in the disk-puzzle room BELOW the
            -- Sanctum (GOB_) and the old x/z-only drift read it as "0m away"
            local drift = math.sqrt((vx - tx) ^ 2 + (vy - py) ^ 2 + (vz - tz) ^ 2)
            if drift <= WILD_SPOT_SLACK then
                -- keep new groups away from existing ones (no pack-on-pack chain aggro)
                local clash = false
                for _, g in ipairs(groups) do
                    if g.cx then
                        local dy = (g.cy or py) - vy
                        local d3 = math.sqrt((vx - g.cx) ^ 2 + dy * dy + (vz - g.cz) ^ 2)
                        if d3 < WILD_GROUP_GAP then
                            clash = true break
                        end
                    end
                end
                if not clash then return vx, vy, vz, radius end
            end
        end
    end
    return nil
end

-- spawn one mob at a position; returns the created guid (or nil).
-- Raw CreateAt refuses even FindValidPosition-validated spots in cramped interiors
-- (in-game v3.15: every member spawn failed on walkable ground), so instead we use
-- the PROVEN anchor route (CreateAtObject: engine solves placement at the host) and
-- then AppearAtPosition to move the mob out to the target spot - with
-- PreventTeleportOnFailure=0 the engine falls back to the nearest valid position on
-- its own if the exact spot is bad. A delayed verify pass logs the final position so
-- playtests can confirm the mob actually left the host's feet.
local function spawnWildMob(entry, host, x, y, z, base, doEquip, faction, groupTier, isBoss)
    local ok, created = pcall(function ()
        local mob = Osi.CreateAtObject(entry.id, host, 1, 0, "", 1)
        if not mob or mob == "" then
            log("wild: CreateAtObject failed for", entry.id)
            return nil
        end
        local okA = pcall(Osi.AppearAtPosition, mob, x, y, z, 0, "", "", 0)
        if not okA then
            log("wild: AppearAtPosition errored for", mob, "- it stays near the host!")
        end
        if faction then
            -- NOTE: GetFaction right after SetFaction returns the STALE template
            -- default (verified in-game: spawn lines showed old factions while the
            -- combat discovery later showed Evil NPC) - verified in the 500ms check
            pcall(Osi.SetFaction, mob, faction)
        end
        -- NO Osi.SetLevel here (game hard-crash 2026-11-01: pcall(Osi.SetLevel) faulted
        -- inside OsirisWrappers::CallWrapper -> bg3.exe from THIS line; pcall cannot
        -- survive engine faults - and per v3.3 SetLevel only sets the level NUMBER, it
        -- does NOT rescale fixed monster stat blocks; difficulty is controlled at PICK
        -- time via gatedPool's native-stat gates, so the call was decorative).
        -- self-correction on the template's NATIVE level: a native lvl-10 caster with
        -- "hp 7" passes every pick gate, so verify and despawn (team templates keep
        -- their baked LevelOverride and are exempt, as before)
        if entry.nm then FlavorNameFix(mob, entry.nm) end   -- blank-name fallback (Flavor.lua); moved BEFORE the despawn branch (v3.30) so even STUCK survivors get named
        if not entry.fixedLevel then
            local okLv, lvlNow = pcall(Osi.GetLevel, mob)
            local n = okLv and tonumber(lvlNow) or nil
            if n and n > base + LEVEL_JITTER + OVERLEVEL_TOLERANCE then
                log("wild: over-level despawn:", entry.id, "lvl", n, "> base", base)
                -- v3.30: retry-ladder delete (Common.lua) - 3s settle, then retry at
                -- +10/30/90s if the mob somehow got into combat (a single skip used to
                -- leave the mob alive forever, nameless, in the fight - owner report).
                ScheduleOverlevelDelete(mob, entry.id, "wild:")
                return nil
            end
        end
        markSpawned(mob)
        tagAsOurs(mob)
        if doEquip then EquipMob(mob, base, entry, groupTier, isBoss) end
        -- NOTE: no SetFaction / no SetHostileAndEnterCombat here - the group stays put
        -- and neutral until the player walks into WILD_AGGRO_RANGE (monitor below)
        -- verify (deferred: appear + faction change resolve next frame)
        pcall(Ext.Timer.WaitFor, 500, function ()
            local okP, mx, my, mz = pcall(Osi.GetPosition, mob)
            if okP and type(mx) == "number" then
                local drift = math.sqrt((mx - x) ^ 2 + (my - y) ^ 2 + (mz - z) ^ 2)
                local fac = "-"
                if faction then
                    local okF, f = pcall(Osi.GetFaction, mob)
                    if okF then fac = tostring(f) end
                end
                log("wild: member placed, drift", string.format("%.1fm", drift), fac)
            end
        end)
        return mob
    end)
    return ok and created or nil
end

-- role-composed teams (iteration 3; v3.29 composer pieces moved to Common.lua so
-- Chaos.lua's reinforce() can run the same engine) --------------------------------
-- TEAM_PROFS/TEAM_FILL/teamSlots/teamLevelFor/teamEntry are shared globals now.
-- v3.29: one donor race per group (raceKey) so a squad LOOKS like a squad.

local function aggroGroup(group, player)
    for _, guid in ipairs(group.members) do
        pcall(Osi.SetFaction, guid, EVIL)
        pcall(Osi.SetHostileAndEnterCombat, EVIL, HERO, guid, player)
    end
    -- no instant backoff (owner 2026-11-01): arm only if the monitor later
    -- confirms a REAL fight (see pendingEngage note at the constants)
    pendingEngage = { id = group.id, members = group.members, combatMs = 0, goneMs = 0 }
    log("wild: group", group.id, "aggroed by", player, "(", #group.members,
        "mobs ); backoff arms only after a real fight")
end

local function spawnWildGroup(host, base)
    local theme = themeFor(currentLevel)
    local themedPool = nil
    if theme then
        themedPool = themedPoolFor(theme, base)
        if #themedPool == 0 then
            log("wild: no themed pool for", theme.name, "at lvl", base, "- skipping")
            return
        end
    end
    local etype = theme and theme.name or wildType(base)
    if not etype then log("wild: no viable pool at level", base); return end

    -- tier roll (owner spec)
    local roll
    if WILD_FORCE_TIER then
        roll = 99   -- consumes the one-shot test override
        log("wild: forced tier", WILD_FORCE_TIER, "(test knob consumed)")
        WILD_FORCE_TIER = nil
    else
        roll = rand(1, 100)
    end
    local tier = roll <= 80 and 1 or (roll <= 98 and 2 or 3)

    -- per-group faction roll (owner spec: neutral "travelers" ONLY as an
    -- all-player-race Humanoid group - every other type/theme is a red enemy pack;
    -- a neutral roll restricts members to pr = true entries so the group is FULL of
    -- player races, never mixed)
    local groupFaction = WILD_EVIL_FACTION
    local neutralPool = nil
    if not theme and etype == "Humanoid" and rand(1, 100) <= WILD_EVIL_CHANCE then
        neutralPool = {}
        for _, e in ipairs(gatedPool("Humanoid", base) or {}) do
            if e.pr then neutralPool[#neutralPool + 1] = e end
        end
        if #neutralPool > 0 then
            groupFaction = nil   -- template default = harmless yellow travelers
        else
            neutralPool = nil   -- no player races available at this level - stay evil
        end
    end
    local count = rand(2, 6)
    local leaderSlots = {}
    local boss = false   -- ⚠️ must stay local + reset per group: a leaked global kept
                         -- the "+3 lvl bump / BOSS prefix" alive for every later group
    if tier == 2 then count = count + rand(1, 4); leaderSlots = { 2 } end
    if tier == 3 then count = count + rand(2, 8); leaderSlots = { 2, 3 }; boss = true end
    count = math.min(count, 12)
    local slotMap = {}
    for _, s in ipairs(leaderSlots) do slotMap[s] = true end

    -- spawn position: valid ground in an out-of-sight ring around the player
    local okP, px, py, pz = pcall(Osi.GetPosition, host)
    if not okP or type(px) ~= "number" then
        log("wild: GetPosition failed, skipping")
        return
    end
    local x, y, z, radius = findGroupSpot(px, py, pz, host)
    if not x then
        log("wild: no valid spot found within", WILD_SPAWN_MIN .. "-" .. WILD_SPAWN_MAX ..
            "m (cramped interiors?), skipping this heartbeat")
        return
    end

    nextGroupId = nextGroupId + 1
    local group = { id = nextGroupId, members = {}, type = etype,
                    faction = groupFaction, cx = x, cy = y, cz = z,
                    ttlMs = rand(WILD_EXPIRE_MIN, WILD_EXPIRE_MAX) * 60000 }
    -- team mode: compose class-teams for humanoid evil packs (iteration 3)
    local teamMode = WILD_TEAMS and etype == "Humanoid" and groupFaction
                     and not themedPool and not neutralPool
                     and CHAOS_TEAMS ~= nil
    local teamSlotList
    local teamRaceKey   -- v3.29 race coherence: ONE donor race for the whole squad
    if teamMode then
        teamSlotList = teamSlots(count)
        local races = donorRaces()
        teamRaceKey = #races > 0 and races[rand(1, #races)] or nil
        log("wild: team mode -", table.concat(teamSlotList, "/"),
            "race", teamRaceKey or "?")
    end
    for i = 1, count do
        local entry
        if teamMode then
            local role = teamSlotList[i]
            -- leader/boss slots are rolled a couple of levels up (still baked templates)
            local bump = (boss and i == 1) and 3 or (slotMap[i] and 2 or nil)
            entry = teamEntry(role, teamLevelFor(base, bump), teamRaceKey)
            if not entry then
                log("wild: team template missing for", role, "- falling back to pool")
            end
        end
        if not entry then
            if neutralPool then
                entry = neutralPool[rand(1, #neutralPool)]
            elseif themedPool then
                entry = themedPool[rand(1, #themedPool)]
            else
                local pool = gatedPool(etype, base) or gatedPool(DEFAULT_TYPES[rand(1, #DEFAULT_TYPES)], base)
                if not pool then break end
                entry = pool[rand(1, #pool)]
            end
        end
        -- per-member jitter around the validated group center (WILD_CLUSTER/2 each way)
        local jitter = rand(-WILD_CLUSTER, WILD_CLUSTER) * 0.5
        local jitterZ = rand(-WILD_CLUSTER, WILD_CLUSTER) * 0.5
        -- equipment goes to anyone with a proficiency group (innate attackers get
        -- nothing from EquipMob anyway); themed pools would have broken the old
        -- etype == "Humanoid" check (goblin warband is not a type name)
        local doEquip = (entry.prof ~= nil and entry.prof ~= "")
        local guid = spawnWildMob(entry, host, x + jitter, y, z + jitterZ, base, doEquip,
                                  groupFaction, tier, boss and i == 1)
        -- failed team slot (CHAOST template unregistered/broken) must never leave an
        -- empty group (owner 2026-11-01: "group spawn FAILED (no members)" x5 after a
        -- root-template registration failure) - retry the slot with a plain pool mob.
        if not guid and teamMode and entry.fixedLevel then
            local pool = gatedPool(etype, base)
            if pool then
                pool = poolForRace(pool, teamRaceKey) or pool   -- keep the squad coherent
                entry = pool[rand(1, #pool)]
                doEquip = (entry.prof ~= nil and entry.prof ~= "")
                log("wild: team slot failed - pool retry:", entry.id)
                guid = spawnWildMob(entry, host, x + jitter, y, z + jitterZ, base, doEquip,
                                    groupFaction, tier, boss and i == 1)
            end
        end
        if guid then
            group.members[#group.members + 1] = guid
            if boss and i == 1 then
                log("wild: boss spawned:", FlavorLeaderCommon(guid, true))
            elseif slotMap[i] then
                log("wild: leader", FlavorLeaderCommon(guid, false))
            end
        end
    end

    if #group.members == 0 then
        log("wild: group spawn FAILED (no members)")
        return
    end
    groups[#groups + 1] = group
    log("wild: spawned group", nextGroupId, "tier", tier, "(roll", roll .. ")", #group.members, "mobs,",
        groupFaction and "(evil pack)" or "(neutral travelers)",
        "type", etype, "at ~", radius .. "m")
    -- subtle world-flavor announcement (client toast); tier 3 earns the scary wording
    if tier == 3 then
        Announce("The wilds stir - a dangerous horde gathers nearby...")
    elseif groupFaction then
        Announce("A hostile warband prowls nearby...")
    else
        Announce("Travelers pass through the area...")
    end
    return true
end

-- heartbeat: try to spawn a wild group while exploring
local lastCrimeRegion = ""
-- heartbeat self-diagnosis (owner 2026-11-01: a 10-min dry spell was unreadable -
-- every gate was a silent return). Reason lines on gate-reason changes, re-stated
-- every 8 ticks (~12 min) if still blocked by the same gate.
local idleReason, idleTicks = "", 0
local function wildIdle(reason)
    if reason ~= idleReason then
        idleReason, idleTicks = reason, 1
        log("wild: no spawn -", reason)
    else
        idleTicks = idleTicks + 1
        if idleTicks % 8 == 0 then
            log("wild: still blocked -", idleReason, "(~" .. math.floor(idleTicks * WILD_HEARTBEAT_MS / 60000) .. "min)")
        end
    end
end
local function heartbeat()
    pcall(Ext.Timer.WaitFor, WILD_HEARTBEAT_MS, heartbeat)
    local allowed = false
    for _, p in ipairs(WILD_LEVEL_PATTERNS) do
        if currentLevel:find(p) then allowed = true break end
    end
    if not allowed then return end
    if not CHAOS_STATE.wilds then return end   -- in-game toggle (Toggle.lua shout): no new groups
    if hostAtCamp() then
        wildIdle("host CAMPED (TeleportedToCamp latched - check camp events fire)")
        return
    end
    local host = Osi.GetHostCharacter()
    if not host or host == "" then wildIdle("no host character") return end
    -- crime-region sub-gate (owner 2026-11-02): the grove ENTRANCE courtyard (Wyll,
    -- tieflings) is ON WLD_Main_A - the level gate cannot exempt it, but vanilla
    -- gives it its own crime region (WLD_Main_A_DEN, "DEN" = the tiefling den in
    -- story naming). While the host's crime region matches a safe pattern, no
    -- spawns. Transitions are logged to map more subregions (e.g. _SHED).
    local crime = ""
    local okCR, cr = pcall(Osi.CharacterGetCrimeRegion, host)
    if okCR and cr then crime = tostring(cr) end
    if crime ~= lastCrimeRegion then
        log("wild: crime-region ->", crime ~= "" and crime or "(nil)")
        lastCrimeRegion = crime
    end
    for _, p in ipairs(WILD_SAFE_CRIME_PATTERNS) do
        if crime:find(p) then
            wildIdle("safe haven (crime region " .. crime .. ")")
            return
        end
    end
    -- safe havens first (grove/camp/cinematics beat the ^WLD_ allowance)
    for _, p in ipairs(WILD_SAFE_PATTERNS) do
        if currentLevel:find(p) then
            wildIdle("safe haven (level " .. currentLevel .. ")")
            return
        end
    end
    if #groups >= WILD_MAX_GROUPS then wildIdle("max groups (" .. #groups .. ")") return end
    if backoffMs > 0 then                       -- encounter cooldown (owner: no back-to-back combat)
        wildIdle("encounter backoff ~" .. math.ceil(backoffMs / 60000) .. "min left")
        return
    end
    local okC, inCombat = pcall(Osi.IsInCombat, host)
    if okC and inCombat == 1 then wildIdle("host in combat") return end
    local chance
    if WILD_TEST then
        chance = 100
    else
        chance = math.min(100, WILD_CHANCE + wildMisses * rand(WILD_STACK_MIN, WILD_STACK_MAX))
    end
    local r = rand(1, 100)
    if r > chance then
        wildMisses = wildMisses + 1
        wildIdle("chance roll " .. r .. " (need <=" .. chance .. ", miss " .. wildMisses .. ")")
        return
    end
    idleReason = ""   -- passed every gate: this heartbeat rolls for real
    local okL, hostLevel = pcall(Osi.GetLevel, host)
    local base = (okL and tonumber(hostLevel)) or 3
    if spawnWildGroup(host, base) then
        if wildMisses > 0 then
            log("wild: stack reset (spawned after", wildMisses, "misses)")
        end
        wildMisses = 0
    else
        -- roll passed but NOTHING landed (no pool / no valid spot / empty group):
        -- still a miss for the stack - the owner's complaint was dry spells with
        -- zero groups, not zero rolls
        wildMisses = wildMisses + 1
        wildIdle("triggered but no group - stack +1 (miss " .. wildMisses .. ")")
    end
end

-- proximity monitor: the group turns hostile only when the player gets close
local function monitor()
    pcall(Ext.Timer.WaitFor, WILD_MONITOR_MS, monitor)
    if backoffMs > 0 then backoffMs = backoffMs - WILD_MONITOR_MS end
    -- pending verdict on the last aggroed group (it left `groups` when aggroed,
    -- so this runs even with no tracked groups; frozen while camped - combat
    -- cannot happen at camp, it resolves once the party is back in the world)
    if pendingEngage then
        local anyCombat = false
        for _, guid in ipairs(pendingEngage.members) do
            local okI, ic = pcall(Osi.IsInCombat, guid)
            if okI and ic == 1 then anyCombat = true break end
        end
        if anyCombat then
            pendingEngage.combatMs = pendingEngage.combatMs + WILD_MONITOR_MS
            pendingEngage.goneMs = 0
            if pendingEngage.combatMs >= WILD_REAL_COMBAT_MS then
                backoffMs = rand(WILD_BACKOFF_MIN, WILD_BACKOFF_MAX) * 60000
                log("wild: real fight confirmed (group", pendingEngage.id ..
                    ") - backoff", math.floor(backoffMs / 60000) .. "min")
                pendingEngage = nil
            end
        else
            pendingEngage.goneMs = pendingEngage.goneMs + WILD_MONITOR_MS
            if pendingEngage.goneMs >= WILD_ENGAGE_GRACE_MS then
                if pendingEngage.combatMs > 0 then
                    log("wild: group", pendingEngage.id, "fight lasted ~",
                        math.floor(pendingEngage.combatMs / 1000) ..
                        "s - fizzle (anomaly), no backoff")
                else
                    log("wild: group", pendingEngage.id, "never engaged (aggro fizzled)",
                        "- anomaly, no backoff")
                end
                pendingEngage = nil
            end
        end
    end
    if #groups == 0 then return end
    if hostAtCamp() then return end   -- camp guard: groups idle (no aggro, no expiry) while camped
    local players = factGuids("DB_Players", 1)
    local host = Osi.GetHostCharacter()
    if host and host ~= "" then players[#players + 1] = host end
    if #players == 0 then return end

    local remaining = {}
    for _, group in ipairs(groups) do
        local nearest, nearDist = nil, math.huge
        for _, guid in ipairs(group.members) do
            local okM, mx, my, mz = pcall(Osi.GetPosition, guid)
            if okM then
                for _, p in ipairs(players) do
                    local okP, px, py, pz = pcall(Osi.GetPosition, p)
                    if okP then
                        -- 3D distance: a group on the floor below (the GOB_ Sanctum
                        -- disk-puzzle room) must NOT aggro through the ceiling
                        local d2 = (mx - px) ^ 2 + (my - py) ^ 2 + (mz - pz) ^ 2
                        if d2 < nearDist then nearest, nearDist = p, d2 end
                    end
                end
            end
        end
        if nearDist <= WILD_AGGRO_RANGE * WILD_AGGRO_RANGE and group.faction then
            aggroGroup(group, nearest)   -- neutral travelers never auto-aggro
        elseif nearDist <= WILD_WATCHED_M * WILD_WATCHED_M then
            remaining[#remaining + 1] = group   -- watched: expiry clock holds
        else
            -- expire quietly out of sight ("they wandered on"); never mid-combat
            group.ttlMs = group.ttlMs - WILD_MONITOR_MS
            group.ticks = (group.ticks or 0) + 1
            if group.ticks % WILD_COUNTDOWN_EVERY == 0 then
                log("wild: group", group.id, "despawns in ~",
                    math.max(1, math.ceil(group.ttlMs / 60000)), "min")
            end
            local inCombat = false
            for _, guid in ipairs(group.members) do
                local okI, ic = pcall(Osi.IsInCombat, guid)
                if okI and ic == 1 then inCombat = true break end
            end
            if group.ttlMs <= 0 and not inCombat then
                for _, guid in ipairs(group.members) do
                    pcall(Osi.RequestDeleteTemporary, guid)
                end
                log("wild: group", group.id, "expired (", #group.members, "mobs wandered on )")
            else
                remaining[#remaining + 1] = group
            end
        end
    end
    groups = remaining
end

-- one-line wild-pipeline snapshot for the !chaos_status console command (Chaos.lua):
-- gate verdict without waiting for the next heartbeat, backoff/campers live values.
WILD_STATUS = function ()
    local n = 0
    for _ in pairs(campers) do n = n + 1 end
    local lo = math.min(100, WILD_CHANCE + wildMisses * WILD_STACK_MIN)
    local hi = math.min(100, WILD_CHANCE + wildMisses * WILD_STACK_MAX)
    return string.format(
        "wild: lvl %s | groups %d/%d | backoff %dmin | campers %d | crime %s | fight %s | misses %d (next %d-%d%%) | gate %s",
        currentLevel, #groups, WILD_MAX_GROUPS, math.ceil(backoffMs / 60000), n,
        lastCrimeRegion ~= "" and lastCrimeRegion or "-",
        pendingEngage and (pendingEngage.combatMs > 0
            and ("~" .. math.floor(pendingEngage.combatMs / 1000) .. "s, arming?")
            or "pending") or "-",
        wildMisses, lo, hi,
        idleReason ~= "" and ("blocked: " .. idleReason) or "clear")
end

-- listeners -------------------------------------------------------------------
pcall(function ()
    Ext.Osiris.RegisterListener("LevelLoaded", 1, "after", function (level)
        currentLevel = tostring(level)
        groups = {}   -- old level's wilds are gone after a level swap
        campers = {}  -- fast-travel can swap levels without TeleportedFromCamp
        -- explicit gate verdict on EVERY level entry (owner 2026-11-02): definite
        -- proof the safe/theme patterns matched - a silently-missed pattern (like the
        -- old GOB_/UND_ that never matched any real level) shows up here immediately.
        local safeHit, openHit
        for _, p in ipairs(WILD_SAFE_PATTERNS) do
            if currentLevel:find(p) then safeHit = p break end
        end
        if safeHit then
            log("wild: gate SAFE", currentLevel, "(matched", safeHit .. ")")
        else
            for _, p in ipairs(WILD_LEVEL_PATTERNS) do
                if currentLevel:find(p) then openHit = p break end
            end
            if openHit then
                local th = themeFor(currentLevel)
                log("wild: gate OPEN", currentLevel,
                    "(matched", openHit .. ", theme:", th and th.name or "default mix", ")")
            else
                log("wild: gate CLOSED", currentLevel, "(no pattern matched)")
            end
        end
        -- region discovery (owner 2026-11-02): the grove entrance courtyard is on
        -- WLD_Main_A and can't be exempted by level name; log the Osiris region and
        -- crime-region strings per level so safe havens can be carved out next.
        local host = Osi.GetHostCharacter()
        if host and host ~= "" then
            local okR, region = pcall(Osi.GetRegion, host)
            if okR and region and region ~= "" then
                log("wild: region", currentLevel, "=", tostring(region))
            end
            local okCR, crime = pcall(Osi.CharacterGetCrimeRegion, host)
            if okCR and crime and crime ~= "" then
                log("wild: crime-region", currentLevel, "=", tostring(crime))
            end
        end
    end)
    -- camp-teleport pair = the only "we are camping" signal (see campers note above);
    -- the logs double as the playtest probe that these events fire for the camp UI
    Ext.Osiris.RegisterListener("TeleportedToCamp", 1, "after", function (char)
        campers[tostring(char)] = true
        log("wild: at CAMP (", tostring(char) .. ") - spawns + aggro paused")
    end)
    Ext.Osiris.RegisterListener("TeleportedFromCamp", 1, "after", function (char)
        campers[tostring(char)] = nil
        if next(campers) == nil then log("wild: camp done - world active again") end
    end)
    Ext.Events.SessionLoaded:Subscribe(function ()
        log("Wild.lua loaded (level gate:", table.concat(WILD_LEVEL_PATTERNS, " / "), ")")
        pcall(Ext.Timer.WaitFor, WILD_HEARTBEAT_MS, heartbeat)
        pcall(Ext.Timer.WaitFor, WILD_MONITOR_MS, monitor)
    end)
end)
